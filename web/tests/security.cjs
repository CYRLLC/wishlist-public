  await assertSucceeds(updateDoc(doc(db('a'),'gift_coupons','gift'),{ title:'新名稱',updatedAt:Date.now() }))
  await assertFails(updateDoc(doc(db('a'),'gift_coupons','gift'),{ remainingUses:100 }))
  await assertFails(updateDoc(doc(db('b'),'gift_coupons','gift'),{ remainingUses:100 }))
