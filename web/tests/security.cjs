test('gift redemption is idempotent, bounded and reversible only by members', async () => {
  await assert.rejects(api.redeemGiftCoupon.run({ auth:auth('c'),data:{ couponId:'gift',requestId:'r-out' } }))
  const twice = await Promise.allSettled([1,2].map(() => api.redeemGiftCoupon.run({ auth:auth('b'),data:{ couponId:'gift',requestId:'r-1' } })))
  assert.ok(twice.some(r => r.status === 'fulfilled'))
  assert.equal((await admin.doc('gift_coupons/gift').get()).data().remainingUses,2)
  await api.redeemGiftCoupon.run({ auth:auth('a'),data:{ couponId:'gift',requestId:'r-2' } })
  await api.redeemGiftCoupon.run({ auth:auth('b'),data:{ couponId:'gift',requestId:'r-3' } })
  await assert.rejects(api.redeemGiftCoupon.run({ auth:auth('b'),data:{ couponId:'gift',requestId:'r-4' } }))
  assert.equal((await admin.doc('gift_coupons/gift').get()).data().remainingUses,0)
  assert.equal((await getDocs(query(collection(db('b'),'gift_redemptions'),where('coupleId','==','ab')))).size,3)
  await assertFails(getDocs(query(collection(db('c'),'gift_redemptions'),where('coupleId','==','ab'))))
  await assert.rejects(api.undoGiftRedemption.run({ auth:auth('c'),data:{ id:'r-3' } }))
  await api.undoGiftRedemption.run({ auth:auth('b'),data:{ id:'r-3' } })
  await assert.rejects(api.undoGiftRedemption.run({ auth:auth('a'),data:{ id:'r-3' } }))
  assert.equal((await admin.doc('gift_coupons/gift').get()).data().remainingUses,1)
  await admin.doc('gift_redemptions/r-2').update({ createdAt:0 })
  await assert.rejects(api.undoGiftRedemption.run({ auth:auth('a'),data:{ id:'r-2' } }))
  await admin.doc('gift_coupons/expired').set(coupon({ id:'expired',expiresAt:Date.now() - 1 }))
  await assert.rejects(api.redeemGiftCoupon.run({ auth:auth('b'),data:{ couponId:'expired',requestId:'r-5' } }))
  await admin.doc('gift_coupons/later').set(coupon({ id:'later',startsAt:Date.now() + 86400000,expiresAt:Date.now() + 2 * 86400000 }))
  await assert.rejects(api.redeemGiftCoupon.run({ auth:auth('b'),data:{ couponId:'later',requestId:'r-6' } }))
})
test('recurring tasks reopen after approval and stale balances reconcile', async () => {
  await admin.doc('tasks/daily').set({ id:'daily',coupleId:'ab',creatorId:'a',claimerId:'b',status:'claimed',points:3,recurrence:'daily',title:'洗碗' })
  await api.settlePoints.run({ auth:auth('a'),data:{ action:'approveTask',id:'daily' } })
  const task = (await admin.doc('tasks/daily').get()).data()
  assert.equal(task.status,'available'); assert.equal(task.claimerId,null); assert.equal(task.completedCount,1)
  await assert.rejects(api.settlePoints.run({ auth:auth('a'),data:{ action:'approveTask',id:'daily' } }))
  await assertSucceeds(updateDoc(doc(db('b'),'tasks','daily'),{ status:'claimed',claimerId:'b',claimNote:'again',claimedAt:Date.now() }))
  await admin.doc('users/b').update({ points:0 })
  const { points } = await api.reconcilePoints.run({ auth:auth('b'),data:{} })
  assert.ok(points > 0)
  assert.equal((await admin.doc('users/b').get()).data().points,points)
})
